import { createContext, useContext } from 'react';
import type { I18nText, Lang } from './types';

const STORAGE_KEY = 'pathcoach.lang';

export const strings = {
  tagline: {
    en: 'A clinically-oriented slide-reading coach for pathology beginners',
    zh: '面向病理新人的临床导向阅片训练工具',
  },
  underConstruction: {
    en: 'Under construction. The case library opens after the pre-test is available.',
    zh: '建设中。练前测上线后才会开放病例库。',
  },
  disclaimer: {
    en: 'For education only. Not for diagnostic use.',
    zh: '仅供学习，不可用于诊断。',
  },
  trialViewer: { en: 'Viewer trial (non-study slide)', zh: '浏览器试验（非练习切片）' },
  back: { en: 'Back', zh: '返回' },
  attribution: {
    en: 'Slides: The results shown here are in whole or part based upon data generated by the TCGA Research Network: https://www.cancer.gov/tcga.',
    zh: '切片：本站展示的结果全部或部分基于 TCGA Research Network 生成的数据：https://www.cancer.gov/tcga。',
  },
} satisfies Record<string, I18nText>;

export function initialLang(): Lang {
  const saved = localStorage.getItem(STORAGE_KEY);
  return saved === 'zh' || saved === 'en' ? saved : 'en';
}

export function saveLang(lang: Lang): void {
  localStorage.setItem(STORAGE_KEY, lang);
}

export const LangContext = createContext<Lang>('en');

export function useT(): (text: I18nText) => string {
  const lang = useContext(LangContext);
  return (text) => text[lang];
}
